package com.example.chatapp.network

/**
 * Определяет, является ли пользовательское сообщение математическим запросом.
 * Используется для выбора специализированного system-промпта.
 */
object MathRequestDetector {

    private val MATH_KEYWORDS = listOf(
        // Русские ключевые слова
        "реши", "решить", "решение", "решаем",
        "уравнение", "уравнения",
        "пример", "примеры",
        "посчитай", "посчитать", "подсчитай", "подсчитать",
        "вычисли", "вычислить", "вычислите",
        "калькулятор",
        "формула", "формулы", "формулу",
        "производная", "производную", "производной",
        "интеграл", "интеграла", "интегрирование",
        "проценты", "процент", "процентов",
        "среднее", "средняя", "среднюю", "среднего",
        "арифметическое", "арифметическая",
        "корень", "квадратный корень",
        "степень", "степени",
        "дробь", "дроби", "дробей",
        "числитель", "знаменатель",
        "сумма", "разность", "произведение", "частное",
        "логарифм", "логарифма",
        "синус", "косинус", "тангенс", "котангенс",
        "sin", "cos", "tan", "ctg", "tg",
        "неравенство", "неравенства",
        "система уравнений",
        "матрица", "матрицу", "определитель",
        "предел", "лимит",
        "факториал",
        "биссектриса", "медиана", "гипотенуза",
        "теорема", "теоремы",
        "площадь", "периметр", "объём", "объем",
        "диаметр", "радиус",
        "x =", "y =",
        "сколько будет",
        "найди значение", "найти значение",
        "упрости", "упростить", "упростите",
        "разложи", "разложить",
        "докажи", "доказать",
        "оценка", "оценки", "оценку",
        "балл", "баллы", "баллов",

        // Английские ключевые слова
        "solve", "equation", "calculate", "compute",
        "derivative", "integral", "integrate",
        "percentage", "percent",
        "average", "mean", "median",
        "formula", "sqrt", "square root",
        "fraction", "exponent",
        "logarithm", "factorial",
        "simplify", "factor"
    )

    private val MATH_OPERATOR_PATTERN = Regex(
        """(?:^|\s)[\d]+\s*[+\-*/×÷^]\s*[\d]+"""
    )

    private val MATH_EQUATION_PATTERN = Regex(
        """[a-zA-Zа-яА-ЯёЁ\d]+\s*[+\-*/×÷]\s*[a-zA-Zа-яА-ЯёЁ\d]+\s*=\s*[a-zA-Zа-яА-ЯёЁ\d]"""
    )

    /**
     * Проверяет, является ли сообщение математическим запросом.
     */
    fun isMathQuery(message: String): Boolean {
        if (message.isBlank()) return false
        val lower = message.lowercase().trim()

        // Проверяем ключевые слова
        if (MATH_KEYWORDS.any { keyword -> lower.contains(keyword) }) {
            return true
        }

        // Проверяем арифметические паттерны (5 + 3, 10 * 2)
        if (MATH_OPERATOR_PATTERN.containsMatchIn(lower)) {
            return true
        }

        // Проверяем паттерн уравнения (x + 5 = 10)
        if (MATH_EQUATION_PATTERN.containsMatchIn(lower)) {
            return true
        }

        return false
    }
}
